export function resolveLanguage(setting) {
    if (LANGUAGES.includes(setting))
        return setting;

    const locale = GLib.get_language_names()[0] ?? 'en';
    return locale.toLowerCase().startsWith('pt') ? 'pt-BR' : 'en';
}

export function createTranslator(setting) {
    const language = resolveLanguage(setting);
    const table = STRINGS[language];

    return (key, params = {}) => {
        const template = table[key] ?? STRINGS['pt-BR'][key] ?? key;
        return template.replace(/\{(\w+)\}/gu, (match, name) =>
            name in params ? String(params[name]) : match);
    };
}
